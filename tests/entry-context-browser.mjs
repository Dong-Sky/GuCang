// Isolated form and fault regression. All network calls are fenced to localhost.
import assert from 'node:assert/strict';
import { pathToFileURL } from 'node:url';
import { mkdir } from 'node:fs/promises';
import { startMockSupabase } from './mock-supabase.mjs';
const { chromium }=await import(pathToFileURL(process.env.GUCANG_PLAYWRIGHT_PATH).href);
const fixture=await startMockSupabase({count:12});
fixture.db.locations.push({...fixture.db.locations[0],id:'50000000-0000-4000-8000-000000000002',name:'另一个盒子'});
const [a,b]=fixture.db.locations;
const browser=await chromium.launch({headless:true,executablePath:process.env.GUCANG_BROWSER_EXECUTABLE});
await mkdir('.local-test/phase2',{recursive:true});
try {
  for(const width of [390,1280]) {
    const context=await browser.newContext({viewport:{width,height:844},hasTouch:true,serviceWorkers:'block'});
    await context.route('**/*',r=>['localhost','127.0.0.1'].includes(new URL(r.request().url()).hostname)||/^(data|blob):/.test(r.request().url())?r.continue():r.abort());
    const page=await context.newPage(),errors=[];
    page.on('pageerror',e=>errors.push(e.message));
    await page.goto('http://127.0.0.1:3102');
    await page.getByLabel('邮箱',{exact:true}).fill('smoke@example.test');
    await page.getByLabel('密码',{exact:true}).fill('local-test-password');
    await page.getByRole('button',{name:'登录',exact:true}).click();
    await page.getByRole('heading',{name:'本地隔离测试谷仓'}).waitFor();
    await page.getByRole('button',{name:'位置',exact:true}).click();
    await page.getByRole('button',{name:/测试收纳盒/}).click();
    await page.getByRole('button',{name:'添加谷子到这里',exact:true}).click();
    const form=page.locator('.item-form-sheet');
    const location=form.locator('.form-grid > label select');
    const inherit=form.getByRole('checkbox');
    const next=form.getByRole('button',{name:'保存并继续',exact:true});
    const ip=page.getByPlaceholder('搜索或输入 IP');
    await inherit.uncheck();
    assert.match(await form.locator('.entry-location-context').innerText(),/测试收纳盒/);
    assert.equal(await location.inputValue(),a.id);
    await ip.fill('位置连续录入');
    await page.getByPlaceholder('例如：徽章').fill('徽章');
    const photo=await page.evaluate(()=>{const c=document.createElement('canvas');c.width=200;c.height=200;c.getContext('2d').fillRect(0,0,200,200);return c.toDataURL().split(',')[1];});
    await page.locator('#item-photo-gallery').setInputFiles({name:'entry.png',mimeType:'image/png',buffer:Buffer.from(photo,'base64')});
    await page.locator('.photo-preview').waitFor();
    await fetch('http://127.0.0.1:54339/__test/fail-next-upload',{method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify({count:1})});
    const count=fixture.db.item_instances.length;
    await next.click();
    await page.locator('.save-error').waitFor();
    assert.equal(fixture.db.item_instances.length,count+1);
    const created=fixture.db.item_instances.at(-1);
    assert.equal(await inherit.isChecked(),false);
    assert.equal(await location.inputValue(),a.id);
    assert.equal(await page.locator('.photo-preview').count(),1);
    await next.click();
    await page.getByText('上一件已保存，现在录入新的一件。照片和编号已重置。',{exact:true}).waitFor();
    assert.equal(fixture.db.item_instances.length,count+1,'retry must not create another instance');
    assert.equal(await location.inputValue(),a.id,'unchecked metadata must not clear entry location');
    assert.equal(await ip.inputValue(),'');
    assert.equal(await page.getByPlaceholder('例如：徽章').inputValue(),'');
    assert.equal(await page.locator('.photo-preview').count(),0);
    assert.ok(fixture.db.item_images.some(image=>image.item_style_id===created.item_style_id));
    await ip.fill('刷新恢复位置');
    await page.getByText('草稿已保留在本机',{exact:true}).waitFor();
    await page.reload();
    await page.getByRole('heading',{name:'本地隔离测试谷仓'}).waitFor();
    await page.getByRole('button',{name:'添加谷子',exact:true}).click();
    await page.getByRole('button',{name:'继续草稿',exact:true}).click();
    assert.equal(await inherit.isChecked(),false,'checkbox preference survives reload');
    assert.equal(await location.inputValue(),a.id);
    assert.match(await form.locator('.entry-location-context').innerText(),/测试收纳盒/);
    await next.click();
    await page.getByText('上一件已保存，现在录入新的一件。照片和编号已重置。',{exact:true}).waitFor();
    assert.equal(fixture.db.item_instances.length,count+2);
    assert.notEqual(fixture.db.item_instances.at(-1).inventory_code,created.inventory_code);
    assert.equal(await location.inputValue(),a.id);
    await page.screenshot({path:`.local-test/phase2/location-unchecked-${width}.png`});
    await form.getByRole('button',{name:'保存为待完善',exact:true}).click();
    await form.waitFor({state:'hidden'});
    // A fresh ordinary entry must not inherit the previous location workflow.
    await page.getByRole('button',{name:'添加谷子',exact:true}).click();
    await ip.waitFor();
    assert.equal(await form.locator('.entry-location-context').count(),0);
    await inherit.uncheck();
    await location.selectOption(b.id);
    await ip.fill('普通入口');
    await next.click();
    await page.getByText('上一件已保存，现在录入新的一件。照片和编号已重置。',{exact:true}).waitFor();
    assert.equal(await location.inputValue(),'');
    assert.equal(await ip.inputValue(),'');
    // Restoring an ordinary draft from a location page must not override it.
    await ip.fill('普通草稿');
    await form.getByRole('button',{name:'取消',exact:true}).click();
    await page.getByRole('button',{name:'位置',exact:true}).click();
    await page.getByRole('button',{name:/另一个盒子/}).click();
    await page.getByRole('button',{name:'添加谷子到这里',exact:true}).click();
    await page.getByRole('button',{name:'继续草稿',exact:true}).click();
    assert.equal(await location.inputValue(),'');
    assert.equal(await inherit.isChecked(),false);
    assert.equal(await form.locator('.entry-location-context').count(),0);
    await inherit.check();
    await location.selectOption(b.id);
    await next.click();
    await page.getByText('上一件已保存，现在录入新的一件。照片和编号已重置。',{exact:true}).waitFor();
    assert.equal(await location.inputValue(),b.id,'ordinary checked entry still inherits');
    assert.equal(await ip.inputValue(),'普通草稿');
    assert.deepEqual(errors,[]);
    assert.equal(fixture.state().historyHash,fixture.state().initialHistoryHash);
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
    await context.close();
    console.log(`PASS entry context ${width}: unchecked retains location, failed save/retry, refresh restores context, ordinary entry and cross-entry draft isolation`);
  }
} finally {await browser.close();await fixture.close();}
