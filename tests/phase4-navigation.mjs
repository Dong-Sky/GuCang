import assert from 'node:assert/strict';
import {chromium} from './browser-runtime.mjs';
import {mkdir,writeFile} from 'node:fs/promises';
import {startMockSupabase} from './mock-supabase.mjs';
const browser=await chromium.launch({headless:true,executablePath:process.env.GUCANG_BROWSER_EXECUTABLE});
const fixture=await startMockSupabase({count:40});
await mkdir('.local-test/phase4-navigation',{recursive:true});
const context=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true,serviceWorkers:'block'});
await context.route('**/*',r=>['localhost','127.0.0.1'].includes(new URL(r.request().url()).hostname)||/^(data|blob):/.test(r.request().url())?r.continue():r.abort());
const page=await context.newPage();
const dialogs=[];let dismiss=true;
page.on('dialog',async d=>{dialogs.push(d.message());if(dismiss) await d.dismiss();else await d.accept();});
try{
 await page.goto('http://127.0.0.1:3102');
 await page.getByLabel('邮箱',{exact:true}).fill('smoke@example.test');
 await page.getByLabel('密码',{exact:true}).fill('local-test-password');
 await page.getByRole('button',{name:'登录',exact:true}).tap();
 await page.getByRole('heading',{name:'本地隔离测试谷仓'}).waitFor();
 await page.locator('.item-card').first().tap();
 await page.getByRole('button',{name:'管理照片',exact:true}).tap();
 const baseline=JSON.stringify(fixture.db.item_images);
 await page.getByRole('button',{name:'旋转90°',exact:true}).first().tap();
 await page.getByRole('button',{name:'返回详情',exact:true}).tap();
 assert.equal(dialogs.length,1);assert.equal(await page.locator('.saved-photo-manager').count(),1);
 console.log('PASS mobile touch: explicit return asks to discard; cancel preserves editor');
 await page.screenshot({path:'.local-test/phase4-navigation/before-back.png',fullPage:true});
 dialogs.length=0;
 await page.goBack();
 await page.waitForFunction(()=>Boolean(document.querySelector('.saved-photo-manager')));
 await page.waitForTimeout(150);
 const result={scenario:'mobile browser Back with unsaved rotation',dialogs,editorStillVisible:await page.locator('.saved-photo-manager').count()>0,storedPhotosUnchanged:JSON.stringify(fixture.db.item_images)===baseline};
 await page.screenshot({path:'.local-test/phase4-navigation/after-back.png',fullPage:true});
 await writeFile('.local-test/phase4-navigation/result.json',JSON.stringify(result,null,2));
 console.log(JSON.stringify(result));
 assert.ok(result.dialogs.length>0||result.editorStillVisible,'BLOCKER: browser Back silently discards unsaved photo adjustments');
 assert.equal(result.editorStillVisible,true);
 dismiss=false;
 await page.goBack();await page.locator('.saved-photo-manager').waitFor({state:'hidden'});
 assert.equal(await page.getByRole('button',{name:'管理照片',exact:true}).count(),1);
 assert.equal(JSON.stringify(fixture.db.item_images),baseline);
 await page.goBack();await page.getByRole('button',{name:'管理照片',exact:true}).waitFor({state:'hidden'});
 console.log('PASS back cancel preserves edits; confirm returns to detail; next back returns home; database unchanged');
}finally{await context.close();await browser.close();await fixture.close();}
